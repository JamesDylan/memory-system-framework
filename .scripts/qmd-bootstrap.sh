#!/bin/zsh
# Set up qmd search for this vault on any machine. Idempotent; safe to re-run.
# 1. Writes qmd's config (~/.config/qmd/index.yml) from the versioned .scripts/qmd/index.yml,
#    with this clone's path filled in. If the private vault (../memory_private) has a
#    qmd-collection.yml, that collection is added too.
# 1b. Writes ~/.config/qmd/seats.yml: the same config without the private collection, for agent seats.
# 2. Installs git hooks that re-index after every pull.
# 3. Indexes the vault and generates embeddings.
# Needs: qmd (npm install -g @tobilu/qmd). First embed downloads ~1GB of local models.

VAULT="$(cd "$(dirname "$0")/.." && pwd)"
PRIVATE="$(cd "$VAULT/../memory_private" 2>/dev/null && pwd)"
CONF_DIR="${XDG_CONFIG_HOME:-$HOME/.config}/qmd"

command -v qmd >/dev/null 2>&1 || { echo "qmd not installed: npm install -g @tobilu/qmd"; exit 1; }
mkdir -p "$CONF_DIR"

# Keep any existing hand-made config (a regular file, or a symlink to somewhere else) as a backup.
CONF="$CONF_DIR/index.yml"
if [ -e "$CONF" ] || [ -L "$CONF" ]; then
  if [ -L "$CONF" ] || ! grep -q '^# generated by qmd-bootstrap' "$CONF"; then
    mv "$CONF" "$CONF.bak.$(date +%Y%m%d%H%M%S)"
  fi
fi

{
  echo "# generated by qmd-bootstrap.sh from $VAULT/.scripts/qmd/index.yml. Do not edit; re-run the script."
  if [ -n "$PRIVATE" ] && [ -f "$PRIVATE/qmd-collection.yml" ]; then
    # Insert the private collection at the end of `collections:`, just before `models:`.
    sed "s#__VAULT__#$VAULT#" "$VAULT/.scripts/qmd/index.yml" |
      awk -v f="$PRIVATE/qmd-collection.yml" -v p="$PRIVATE" \
        '/^models:/ { while ((getline l < f) > 0) { gsub("__PRIVATE__", p, l); print l } } { print }'
  else
    echo "Note: no private vault collection (expected $VAULT/../memory_private/qmd-collection.yml)." >&2
    sed "s#__VAULT__#$VAULT#" "$VAULT/.scripts/qmd/index.yml"
  fi
} > "$CONF"

# Agent seats search a second index that holds the shared vault only, so a seat can never read private notes.
{
  echo "# generated by qmd-bootstrap.sh from $VAULT/.scripts/qmd/index.yml (shared vault only, for agent seats). Do not edit."
  sed "s#__VAULT__#$VAULT#" "$VAULT/.scripts/qmd/index.yml"
} > "$CONF_DIR/seats.yml"

# Re-index after a pull (merge, fast-forward or rebase). Never replaces a hook the user already has.
HOOKS="$(git -C "$VAULT" rev-parse --git-path hooks 2>/dev/null)"
if [ -n "$HOOKS" ]; then
  case "$HOOKS" in /*) ;; *) HOOKS="$VAULT/$HOOKS" ;; esac
  mkdir -p "$HOOKS"
  for h in post-merge post-rewrite; do
    if [ -e "$HOOKS/$h" ] && ! grep -q 'qmd-bootstrap' "$HOOKS/$h"; then
      echo "Note: $HOOKS/$h exists; add 'qmd update && qmd embed' to it yourself."
    else
      printf '#!/bin/sh\n# installed by qmd-bootstrap.sh\n(qmd update && qmd embed) >/dev/null 2>&1 &\n' > "$HOOKS/$h"
      chmod +x "$HOOKS/$h"
    fi
  done
fi

qmd update && qmd embed && qmd --index seats update && qmd --index seats embed && qmd status
